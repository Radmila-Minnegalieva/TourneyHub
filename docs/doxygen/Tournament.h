#pragma once

#include <string>

/**
 * @file Tournament.h
 * @brief Объявление базового класса турнира.
 *
 * Файл содержит описание класса Tournament,
 * представляющего турнир в системе TourneyHub.
 */

/**
 * @brief Базовый класс турнира.
 *
 * Класс хранит основные параметры турнира:
 * название, максимальное количество участников,
 * текущее количество участников и состояние публикации.
 *
 * Класс предоставляет операции публикации турнира,
 * добавления участников и получения текущего количества участников.
 */
class Tournament
{
public:
    /**
     * @brief Создаёт новый турнир.
     *
     * Инициализирует турнир с указанным названием
     * и максимальным количеством участников.
     *
     * @param name Название турнира.
     * @param maxParticipants Максимально допустимое количество участников.
     */
    Tournament(
        const std::string& name,
        int maxParticipants
    );

    /**
     * @brief Публикует турнир.
     *
     * После вызова метода турнир считается опубликованным.
     */
    void publish();

    /**
     * @brief Добавляет участника в турнир.
     *
     * Участник добавляется только в том случае,
     * если максимальное количество участников ещё не достигнуто.
     *
     * @return true, если участник был успешно добавлен;
     * false, если свободных мест нет.
     */
    bool addParticipant();

    /**
     * @brief Возвращает текущее количество участников.
     *
     * @return Количество зарегистрированных участников турнира.
     */
    int getParticipantsCount() const;

private:
    std::string name; ///< Название турнира.
    int maxParticipants; ///< Максимальное количество участников.
    int participantsCount; ///< Текущее количество участников.
    bool published; ///< Признак публикации турнира.
};